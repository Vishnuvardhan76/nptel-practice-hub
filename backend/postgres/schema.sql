-- NPTEL Practice Hub PostgreSQL Schema

CREATE TABLE IF NOT EXISTS weeks (
    week_number INTEGER PRIMARY KEY,
    title TEXT NOT NULL,
    total_questions INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_number INTEGER NOT NULL REFERENCES weeks(week_number) ON DELETE CASCADE,
    question_number INTEGER NOT NULL,
    question_order INTEGER NOT NULL,
    question_text TEXT NOT NULL,
    marks DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    is_verified INTEGER NOT NULL DEFAULT 0,
    flag_reason TEXT,
    UNIQUE (week_number, question_number)
);

CREATE TABLE IF NOT EXISTS options (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    option_letter TEXT NOT NULL,
    option_order INTEGER NOT NULL,
    option_text TEXT NOT NULL,
    is_correct INTEGER NOT NULL DEFAULT 0,
    UNIQUE (question_id, option_letter),
    UNIQUE (question_id, option_order)
);

CREATE TABLE IF NOT EXISTS practice_sessions (
    session_id TEXT PRIMARY KEY,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    selected_weeks TEXT NOT NULL,
    test_type TEXT NOT NULL,
    question_ids TEXT NOT NULL,
    option_orders TEXT NOT NULL,
    user_answers TEXT DEFAULT '{}',
    is_submitted INTEGER NOT NULL DEFAULT 0,
    submitted_at TIMESTAMP,
    score DOUBLE PRECISION DEFAULT 0.0,
    total_marks DOUBLE PRECISION DEFAULT 0.0,
    correct_count INTEGER DEFAULT 0,
    incorrect_count INTEGER DEFAULT 0,
    unanswered_count INTEGER DEFAULT 0,
    client_id TEXT
);
